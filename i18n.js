  // 'ja-JP' -> 'ja', 'id' / 'in-ID' -> 'id', anything else -> 'en'
  function pick(locale) {
    const base = String(locale || '').toLowerCase().split(/[-_]/)[0];
    if (base === 'ja') return 'ja';
    if (base === 'id' || base === 'in') return 'id';
    return 'en';
  }

  function t(lang, key, params) {
    const table = messages[lang] || messages.en;
    const text = table[key] ?? messages.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (match, name) => (params && name in params ? String(params[name]) : match));
  }

  return { LANGS, messages, pick, t };
